#pragma once // Защита от повторного включения заголовочного файла при компиляции

// Создаем пространство имен ( namespace ), чтобы наши функции не конфликтовали
// с системными или чужими именами. Это аналог пакетов для кода.
namespace ConsoleSystem {

    // Структура ( struct ) — это пользовательский тип данных, который объединяет
    // несколько переменных под одной крышей. Здесь мы храним указатели (дескрипторы)
    // на консольный вывод и ввод.
    struct ConsoleContext {
        void* hOut; // Указатель на поток вывода (наш экран/терминал)
        void* hIn;  // Указатель на поток ввода (наша клавиатура)
    };

    /**
     * Объявление функции инициализации (запуска).
     * Возвращает заполненную структуру ConsoleContext с дескрипторами.
     */
    ConsoleContext init();

    /**
     * Объявление функции записи текста в консоль.
     * @param hOut Куда писать (дескриптор экрана)
     * @param text Указатель на начало строки (массив байтов)
     * @param size Сколько байт нужно записать
     */
    void write(void* hOut, const char* text, unsigned long size);

    /**
     * Перегрузка функции записи для обычных нуль-терминированных строк.
     * Сама вычисляет размер строки через поиск терминатора '\0'.
     */
    void write(void* hOut, const char* text);

    /**
     * Объявление функции чтения из консоли.
     * @param hIn Откуда читать (дескриптор клавиатуры)
     * @param buffer Буфер (массив памяти), куда запишется введенный текст
     * @param size Максимальный размер буфера
     * @return Возвращает количество реально прочитанных байт (тип long)
     */
    long read(void* hIn, char* buffer, unsigned long size);

    /**
     * Объявление функции остановки (завершения) программы.
     * @param exitCode Код завершения программы (0 — успех, остальное — ошибки)
     */
    void shutdown(int exitCode);
} // namespace ConsoleSystem
